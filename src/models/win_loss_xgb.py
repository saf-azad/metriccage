"""Model A — XGBoost binary win/loss classifier.

Conservative regularisation; this is a small-sample tabular problem and
overfitting is the main risk. SHAP analysis runs after every fit.

DEFAULT PARAMS: `train_model_a` merges config.XGB_DEFAULTS ← PHASE2_OVERRIDES
← caller `params`, with early stopping (30 rounds) on the validation slice.
PHASE2_OVERRIDES below (max_depth=5, lr=0.03, n_estimators=600,
min_child_weight=6, reg_alpha=0.3, reg_lambda=1.0, subsample=0.8,
colsample_bytree=0.8) came from the Phase-2 manual grid used by
scripts/train_all.py — NOT the deployed head's params. The PRODUCTION win/loss
head was retrained by scripts/optuna_xgb.py with config.XGB_OPTUNA_TUNED
(80-trial optuna val-AUC search, 2026-05-10) on the pruned 67-feature set;
pass params=XGB_OPTUNA_TUNED to reproduce it through this module.

OUTPUT
    data/processed/model_a_xgb.json     (xgboost native serialisation)
    docs/model_cards/model_a_v{N}.md    (auto-generated by training script)
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from src.config import MODEL_CARDS, PROCESSED, XGB_DEFAULTS

# Phase-2 tuned overrides — used by default by train_all.
PHASE2_OVERRIDES: dict[str, Any] = {
    "max_depth": 5,
    "learning_rate": 0.03,
    "n_estimators": 600,
    "min_child_weight": 6,
    "reg_alpha": 0.3,
    "reg_lambda": 1.0,
    "subsample": 0.8,
    "colsample_bytree": 0.8,
    "objective": "binary:logistic",
    "eval_metric": "logloss",
    "random_state": 42,
}


@dataclass
class TrainResult:
    booster: Any
    metrics: dict[str, float]
    feature_importance: list[tuple[str, float]] = field(default_factory=list)
    best_iteration: int | None = None


def _build_classifier(params: dict | None = None):
    from xgboost import XGBClassifier

    cfg = {**XGB_DEFAULTS, **PHASE2_OVERRIDES, **(params or {})}
    # Early stopping is set on the constructor for newer xgboost versions.
    cfg.setdefault("early_stopping_rounds", 30)
    return XGBClassifier(**cfg)


def train_model_a(
    X_train: pd.DataFrame,
    y_train: pd.Series,
    X_val: pd.DataFrame,
    y_val: pd.Series,
    params: dict | None = None,
) -> TrainResult:
    """Train Model A. Returns (booster, metrics_dict).

    Uses early stopping on the validation slice; final n_iterations is whatever
    converged best on val log-loss.
    """
    from sklearn.metrics import (
        accuracy_score,
        brier_score_loss,
        log_loss,
        roc_auc_score,
    )

    clf = _build_classifier(params)
    try:
        clf.fit(X_train, y_train, eval_set=[(X_val, y_val)], verbose=False)
    except TypeError:
        # Older xgboost API — early_stopping_rounds passed to fit().
        from xgboost import XGBClassifier

        cfg = {**XGB_DEFAULTS, **PHASE2_OVERRIDES, **(params or {})}
        clf = XGBClassifier(**cfg)
        clf.fit(
            X_train,
            y_train,
            eval_set=[(X_val, y_val)],
            early_stopping_rounds=30,
            verbose=False,
        )

    p_val = clf.predict_proba(X_val)[:, 1]
    metrics = {
        "val_logloss": float(log_loss(y_val, np.clip(p_val, 1e-6, 1 - 1e-6))),
        "val_brier": float(brier_score_loss(y_val, p_val)),
        "val_auc": float(roc_auc_score(y_val, p_val)),
        "val_accuracy": float(accuracy_score(y_val, (p_val >= 0.5).astype(int))),
        "n_train": int(len(X_train)),
        "n_val": int(len(X_val)),
    }

    booster = clf.get_booster() if hasattr(clf, "get_booster") else clf
    importance_dict = booster.get_score(importance_type="gain")
    importance = sorted(importance_dict.items(), key=lambda kv: kv[1], reverse=True)
    best_iter = getattr(clf, "best_iteration", None)

    return TrainResult(
        booster=clf,
        metrics=metrics,
        feature_importance=importance,
        best_iteration=int(best_iter) if best_iter is not None else None,
    )


def predict_proba(booster, X: pd.DataFrame) -> pd.Series:
    """Returns P(fighter_a wins) as a Series indexed by X.index.

    Accepts either an XGBClassifier or a raw Booster (uses DMatrix path then).
    """
    if hasattr(booster, "predict_proba"):
        p = booster.predict_proba(X)[:, 1]
    else:
        from xgboost import DMatrix

        dmat = DMatrix(X)
        p = booster.predict(dmat)
    return pd.Series(np.asarray(p), index=X.index, name="p_a")


# --- SHAP -------------------------------------------------------------------


def shap_summary(booster, X: pd.DataFrame, *, max_rows: int = 1500) -> pd.DataFrame:
    """Mean-abs-SHAP per feature on a sample of X. Returns descending DataFrame."""
    import shap

    if len(X) > max_rows:
        X = X.sample(max_rows, random_state=42)
    explainer = shap.TreeExplainer(booster)
    sv = explainer.shap_values(X)
    if isinstance(sv, list):  # multiclass safety
        sv = sv[1]
    mean_abs = np.abs(sv).mean(axis=0)
    return (
        pd.DataFrame({"feature": X.columns, "mean_abs_shap": mean_abs})
        .sort_values("mean_abs_shap", ascending=False)
        .reset_index(drop=True)
    )


def per_fight_shap(booster, X: pd.DataFrame) -> np.ndarray:
    """Full SHAP matrix for X (used for in-card driver explanations)."""
    import shap

    explainer = shap.TreeExplainer(booster)
    sv = explainer.shap_values(X)
    if isinstance(sv, list):
        sv = sv[1]
    return sv


# --- Model card -------------------------------------------------------------


def write_model_card(
    result: TrainResult,
    feature_names: list[str],
    *,
    version: str | None = None,
    notes: str = "",
) -> Path:
    """Emit a Markdown model card per docs/model_cards/. Returns the path written."""
    MODEL_CARDS.mkdir(parents=True, exist_ok=True)
    if version is None:
        version = datetime.now().strftime("%Y%m%d_%H%M%S")
    path = MODEL_CARDS / f"model_a_v{version}.md"

    importance = result.feature_importance[:20]
    imp_lines = "\n".join(f"| {name} | {gain:.4f} |" for name, gain in importance)

    metrics_lines = "\n".join(f"| {k} | {v:.6f} |" for k, v in result.metrics.items())

    body = f"""# Model A — XGBoost (v{version})

## Metrics (validation slice)

| metric | value |
|---|---|
{metrics_lines}

## Hyperparameters
- Phase 2 overrides applied; see `src/models/win_loss_xgb.PHASE2_OVERRIDES`.
- Best iteration: {result.best_iteration}

## Top features (gain)

| feature | gain |
|---|---|
{imp_lines}

## Feature names ({len(feature_names)})

{', '.join(feature_names)}

## Notes
{notes or '_None._'}
"""
    path.write_text(body)
    return path


def save_booster(result: TrainResult, version: str | None = None) -> Path:
    """Persist the booster to data/processed/."""
    PROCESSED.mkdir(parents=True, exist_ok=True)
    if version is None:
        version = datetime.now().strftime("%Y%m%d_%H%M%S")
    path = PROCESSED / f"model_a_xgb_v{version}.json"
    booster = (
        result.booster.get_booster()
        if hasattr(result.booster, "get_booster")
        else result.booster
    )
    booster.save_model(str(path))
    metrics_path = path.with_suffix(".metrics.json")
    metrics_path.write_text(json.dumps(result.metrics, indent=2))
    return path
